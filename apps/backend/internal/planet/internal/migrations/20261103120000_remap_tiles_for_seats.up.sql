    SELECT jsonb_agg(jsonb_set(o.value, '{tile}', to_jsonb(r.to_id + ((o.value->>'tile')::integer - r.from_id))) ORDER BY o.ordinality)
    FROM jsonb_array_elements(e.payload->'cleared') WITH ORDINALITY o
    JOIN tile_remap r ON (o.value->>'tile')::integer >= r.from_id AND (o.value->>'tile')::integer < r.from_id + r.span
), '[]'::jsonb))
