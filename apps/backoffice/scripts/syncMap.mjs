// Copies every board from /map into src/gen/map, each one's manifest and runs, where Vite bundles them, and writes the
// table of them by name, src/gen/map/boards.ts. The page rebuilds a board's tile positions from its runs the first
// time an answer names it (src/boards/places.ts).
import {copyFileSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync} from "node:fs"
import {dirname, join, resolve} from "node:path"
import {fileURLToPath} from "node:url"

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const boardsDir = resolve(root, "..", "..", "map", "boards")
const outDir = join(root, "src", "gen", "map")

const names = readdirSync(boardsDir, {withFileTypes: true})
    .filter(entry => entry.isDirectory())
    .map(entry => entry.name)
    .sort()
if (names.length === 0) throw new Error(`no board in ${boardsDir}`)

const boards = names.map(name => {
    const from = join(boardsDir, name)
    const manifests = readdirSync(from).filter(file => /^board-[0-9a-f]{8}\.json$/.test(file))
    if (manifests.length !== 1) throw new Error(`expected one board-<hash>.json in ${from}, found ${manifests.length}`)
    const [manifestFile] = manifests
    const manifest = JSON.parse(readFileSync(join(from, manifestFile), "utf8"))
    if (manifest.name !== name) throw new Error(`${from}/${manifestFile} names itself ${manifest.name}, not ${name}`)
    return {name, from, manifestFile, manifest, runs: identifierOf(name)}
})

const identifiers = new Set(boards.map(board => board.runs))
if (identifiers.size !== boards.length) throw new Error("two boards' names read as one identifier: rename one")

rmSync(outDir, {recursive: true, force: true})
for (const {name, from, manifestFile, manifest} of boards) {
    mkdirSync(join(outDir, name), {recursive: true})
    for (const file of [manifestFile, manifest.files.runs]) copyFileSync(join(from, file), join(outDir, name, file))
}

const imports = boards.map(({name, manifest, runs}) => `import ${runs} from "./${name}/${manifest.files.runs}?url"`)
const entries = boards.map(({name, manifest, runs}) => `    ${JSON.stringify(name)}: {
        manifest: ${JSON.stringify(manifest, null, 4).replaceAll("\n", "\n        ")},
        runs: ${runs},
    },`)
writeFileSync(join(outDir, "boards.ts"), `// Generated by \`npm run map\` from /map/boards: do not edit.
${imports.join("\n")}

// Every board in /map/boards, by name: its manifest, and the address its runs are served at.
export const BOARDS = {
${entries.join("\n")}
} as const
`)

for (const {name, manifestFile, manifest} of boards) {
    console.log(`src/gen/map/${name} ← map/boards/${name}: ${manifestFile} and ${manifest.files.runs}`)
}

// "earth-1" is earth1Runs.
function identifierOf(name) {
    const words = name.split(/[^A-Za-z0-9]+/).filter(word => word !== "")
    const camel = words.map((word, i) => i === 0 ? word : word[0].toUpperCase() + word.slice(1)).join("")
    return `${/^[0-9]/.test(camel) ? "_" : ""}${camel}Runs`
}
