// Copies the shared tile coordinates from /map into src/gen/map, where Vite bundles it, and names it for the page.
import {copyFileSync, mkdirSync, readdirSync, unlinkSync, writeFileSync} from "node:fs"
import {dirname, join, resolve} from "node:path"
import {fileURLToPath} from "node:url"

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..")
const mapDir = resolve(root, "..", "..", "map")
const outDir = join(root, "src", "gen", "map")
const pattern = /^coordinates-[0-9a-f]{8}\.bin$/

const names = readdirSync(mapDir).filter(name => pattern.test(name))
if (names.length !== 1) throw new Error(`expected one coordinates-<hash>.bin in ${mapDir}, found ${names.length}`)
const [name] = names

mkdirSync(outDir, {recursive: true})
for (const old of readdirSync(outDir).filter(file => pattern.test(file) && file !== name)) unlinkSync(join(outDir, old))
copyFileSync(join(mapDir, name), join(outDir, name))
writeFileSync(join(outDir, "coordinates.ts"),
    `// Generated by \`npm run map\` from /map: do not edit.\nimport url from "./${name}?url"\n\nexport const COORDINATES_URL = url\n`)

console.log(`src/gen/map/${name} ← map/${name}`)
